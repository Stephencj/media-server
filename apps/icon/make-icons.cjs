// Media Server's icon: "Guide" (A2). Two rows of a TV guide on navy, the
// programme on now lit amber with a play mark, and the "now" line through them:
// the channels, the library and the player in one picture.
//   NODE_PATH=<a node_modules with playwright> node apps/icon/make-icons.cjs
// Writes the iPhone icon, the Apple TV brand assets (parallax layers at their
// existing sizes, the App Store stack, the Top Shelf images) and the Fire TV
// launcher icon and banner (vector drawables, in the checkout it runs in).
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');

const NAVY = '#0f1b3d', BLOCK = '#2b3f7a', AMBER = '#f5a524', LINE = '#e9edf8';
const APPS = path.join(__dirname, '..');

// The design on a view vw×100 (square: vw 100). Bars stretch with the width;
// the margin is 13% of the width, as on the square icon.
function shapes(vw, layers) {
  const m = Math.max(13, vw * 0.13), inner = vw - 2 * m, gap = 4;
  const a = inner * 0.405, amber = inner * 0.70, nowX = m + inner * 0.355;
  const rect = (x, y, w, h, rx, fill) => ({ x, y, w, h, rx, fill });
  const out = { back: [rect(0, 0, vw, 100, 0, NAVY)], middle: [], front: [] };
  out.middle.push(rect(m, 27, a, 20, 5, BLOCK), rect(m + a + gap, 27, inner - a - gap, 20, 5, BLOCK),
                  rect(m + amber + gap, 53, inner - amber - gap, 20, 5, BLOCK));
  out.front.push(rect(m, 53, amber, 20, 5, AMBER), rect(nowX - 1.3, 20, 2.6, 60, 1.3, LINE));
  const play = { tri: [m + 9, 57, m + 9, 69, m + 19, 63], fill: NAVY };
  return layers.flatMap((l) => out[l].map((r) => ({ ...r, layer: l }))).concat(layers.includes('front') ? [play] : []);
}

function svg(w, h, layers, zoom = 1) {
  const vh = 100 * zoom, vw = vh * w / h;
  const items = shapes(vw / zoom, layers);
  const body = items.map((s) => s.tri
    ? `<path d="M${s.tri[0]} ${s.tri[1]} L${s.tri[2]} ${s.tri[3]} L${s.tri[4]} ${s.tri[5]} Z" fill="${s.fill}"/>`
    : `<rect x="${s.x}" y="${s.y}" width="${s.w}" height="${s.h}" rx="${s.rx}" fill="${s.fill}"/>`).join('');
  // Zoomed out: the background still covers everything.
  const ox = (vw - vw / zoom) / 2, oy = (vh - 100) / 2;
  const bg = layers.includes('back') ? `<rect x="${-ox}" y="${-oy}" width="${vw}" height="${vh}" fill="${NAVY}"/>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${-ox} ${-oy} ${vw} ${vh}">${bg}${body}</svg>`;
}

// Android vector drawable of the same design: `scale` maps the 100-high design
// into the viewport, offset by (dx, dy).
function vector(wDp, hDp, vw, scale, dx, dy) {
  const n = (v) => +v.toFixed(2);
  const rr = (s) => {
    const x = s.x * scale + dx, y = s.y * scale + dy, w = s.w * scale, h = s.h * scale, r = Math.min(s.rx * scale, w / 2, h / 2);
    return r ? `M${n(x + r)},${n(y)}h${n(w - 2 * r)}a${n(r)},${n(r)} 0,0 1,${n(r)},${n(r)}v${n(h - 2 * r)}a${n(r)},${n(r)} 0,0 1,${n(-r)},${n(r)}h${n(-(w - 2 * r))}a${n(r)},${n(r)} 0,0 1,${n(-r)},${n(-r)}v${n(-(h - 2 * r))}a${n(r)},${n(r)} 0,0 1,${n(r)},${n(-r)}z`
             : `M${n(x)},${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
  };
  const items = shapes(vw, ['middle', 'front']);
  const paths = items.map((s) => {
    const d = s.tri ? `M${n(s.tri[0] * scale + dx)},${n(s.tri[1] * scale + dy)}L${n(s.tri[2] * scale + dx)},${n(s.tri[3] * scale + dy)}L${n(s.tri[4] * scale + dx)},${n(s.tri[5] * scale + dy)}z` : rr(s);
    return `    <path android:fillColor="${s.fill.toUpperCase()}" android:pathData="${d}" />`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/icon/make-icons.cjs: Media Server's "Guide" icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${wDp}dp"
    android:height="${hDp}dp"
    android:viewportWidth="${wDp}"
    android:viewportHeight="${hDp}">
    <path android:fillColor="${NAVY.toUpperCase()}" android:pathData="M0,0h${wDp}v${hDp}h-${wDp}z" />
${paths.join('\n')}
</vector>
`;
}

const size = (file) => {
  const buf = fs.readFileSync(file);   // PNG IHDR
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
};

const tv = path.join(APPS, 'apple-tv/MediaPlayer/Assets.xcassets/AppIcon.brandassets');
const jobs = [[path.join(APPS, 'ios-mobile/MediaServerMobile/Assets.xcassets/AppIcon.appiconset/icon.png'), 1024, 1024, ['back', 'middle', 'front']]];
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);
for (const file of walk(tv).filter((f) => f.endsWith('.png'))) {
  // Each existing image is redrawn at its own size: its layer from its stack layer folder.
  const [w, h] = size(file);
  const appStore = file.includes('App Store');
  const layer = /Back\.imagestacklayer/.test(file) ? ['back']
    : /Middle\.imagestacklayer/.test(file) ? ['middle']
    : /Front\.imagestacklayer/.test(file) ? (appStore ? ['middle', 'front'] : ['front'])
    : ['back', 'middle', 'front'];
  jobs.push([file, w, h, layer, /Top Shelf/.test(file) ? 1.25 : 1]);
}

const res = path.join(APPS, 'fire-tv/app/src/main/res/drawable');
// Launcher icon: 108dp with the design in the middle 72dp (the launcher may crop to 66).
fs.writeFileSync(path.join(res, 'ic_launcher.xml'), vector(108, 108, 100, 0.72, 18, 18));
// Banner: 320×180dp, the guide stretched across: the 100-high design at 1.44× (144dp,
// centred), 320/1.44 design units wide.
fs.writeFileSync(path.join(res, 'banner.xml'), vector(320, 180, 320 / 1.44, 1.44, 0, 18));

(async () => {
  const browser = await chromium.launch().catch(() => chromium.launch({ channel: 'chrome' }));
  const page = await browser.newPage();
  for (const [file, w, h, layers, zoom] of jobs) {
    await page.setViewportSize({ width: w, height: h });
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg(w, h, layers, zoom)}</body></html>`);
    await page.locator('svg').screenshot({ path: file, omitBackground: true });
    console.log(path.relative(APPS, file), `${w}x${h}`, layers.join('+'));
  }
  await browser.close();
})();
